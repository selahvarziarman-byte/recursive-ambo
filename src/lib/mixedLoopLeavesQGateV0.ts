function parseSignedUnit(label: string): OctValue {
  const sign = label.startsWith('-') ? -1 : 1;
  const unitLabel = label.replace(/^[+-]/, '');
  const unit = unitLabel === '1' ? 0 : Number(unitLabel.slice(1));

  return { sign: sign as 1 | -1, unit };
}

function mulKeys(leftKey: string, rightKey: string): string {
  return octKey(octMul(parseSignedUnit(leftKey), parseSignedUnit(rightKey)));
}

/** Multiplicative closure of a set of signed basis elements (fixpoint). */
function closeUnderProduct(seedKeys: string[]): string[] {
  const closed = new Set<string>(seedKeys);
  let changed = true;

  while (changed) {
    changed = false;
    const current = [...closed];

    for (const leftKey of current) {
      for (const rightKey of current) {
        const productKey = mulKeys(leftKey, rightKey);

        if (!closed.has(productKey)) {
          closed.add(productKey);
          changed = true;
        }
      }
    }
  }

  return [...closed].sort();
}

function unitOfKey(key: string): number {
  return parseSignedUnit(key).unit;
}

function dimensionOf(closedKeys: string[]): number {
  return new Set(closedKeys.map(unitOfKey)).size;
}

const Q_SIGNED_KEYS = ['+1', '-1', '+e3', '-e3', '+e5', '-e5', '+e6', '-e6'].sort();

function isSubsetOfQ(closedKeys: string[]): boolean {
  const qSet = new Set(Q_SIGNED_KEYS);

  return closedKeys.every((key) => qSet.has(key));
}

function classifyClosure(closedKeys: string[]): LeavesQClosureOutcome['closureKind'] {
  const dimension = dimensionOf(closedKeys);
  const equalsQ =
    closedKeys.length === Q_SIGNED_KEYS.length &&
    closedKeys.every((key, index) => key === Q_SIGNED_KEYS[index]);

  if (equalsQ) {
    return 'equals-Q';
  }

  if (dimension === 8) {
    return 'full-octonions-8dim';
  }

  if (dimension === 4) {
    return 'quaternion-4dim-not-Q';
  }

  if (dimension <= 2) {
    return 'dim-2-or-smaller';
  }

  return 'other';
}

function mulberry32(seed: number): () => number {
  let state = seed >>> 0;

  return () => {
    state = (state + 0x6d2b79f5) >>> 0;
    let mixed = state;
    mixed = Math.imul(mixed ^ (mixed >>> 15), mixed | 1);
    mixed ^= mixed + Math.imul(mixed ^ (mixed >>> 7), mixed | 61);

    return ((mixed ^ (mixed >>> 14)) >>> 0) / 4294967296;
  };
}

function drawPermutation(size: number, next: () => number): number[] {
  const permutation = Array.from({ length: size }, (_unused, index) => index);

  for (let index = size - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(next() * (index + 1));
    const held = permutation[index];
    permutation[index] = permutation[swapIndex];
    permutation[swapIndex] = held;
  }

  return permutation;
}

