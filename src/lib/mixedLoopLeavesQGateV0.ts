    if (edgeRow.edgeFamily !== 'complement-coupling-edge') {
      continue;
    }

    edges.push({
      edgeId: `compl:${edgeRow.childTokenId}->${edgeRow.complementTokenId}`,
      family: 'complement',
      from: edgeRow.childTokenId,
      to: edgeRow.complementTokenId,
      viaActionSource: null,
      linkUnitKeys: [
        octKey(parseSignedUnit(edgeRow.sourceChildSignedLift)),
        octKey(parseSignedUnit(edgeRow.complementChildSignedLift)),
      ],
      sourceRows: [
        `F1 edgeRows[${edgeRow.edgeId}].sourceChildSignedLift = ${edgeRow.sourceChildSignedLift}`,
        `F1 edgeRows[${edgeRow.edgeId}].complementChildSignedLift = ${edgeRow.complementChildSignedLift}`,
      ],
      underdetermined: false,
    });
