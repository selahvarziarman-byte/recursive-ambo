// ═══ D18 — THE TRUTH VALUE OF AN INSTANCE (the third resolution §1; ADR 0031 §9.19 with §9.20's rider) ═══
// For an instance i on the medium, its VALUE V(i) is the set of views Z through which some path composes to i — the views under which i is
// *also through Z*. Read, never stored; indexed by the stage like everything read. THE ONE OBJECT: the site's own and centroid parts,
// each view's own and centroid parts, and the tokens POCKET · EXHAUSTED · CLOSED are READINGS of the family of values and of nothing
// else — derived once, below, for the card, the witnesses and D19's k. The page keeps COPY-1's sentences; no value is printed as a set.
/** the family of values: every instance key → the views (in the views' order, each once) whose paths compose to it */
export type InstanceValues = Map<string, VertexId[]>;
export function valuesOf(keys: readonly string[], composed: ReadonlyArray<{ view: VertexId; composedTo: ReadonlySet<string> }>): InstanceValues {
  const values: InstanceValues = new Map();
  for (const k of keys) { const V: VertexId[] = []; for (const c of composed) if (c.composedTo.has(k) && !V.includes(c.view)) V.push(c.view); values.set(k, V); }
  return values;
}
/** D7 — an instance is OWN (*not through C or D*) iff its value is empty; the face's (*also through C*) iff not */
export const isOwn = (values: InstanceValues, key: string): boolean => (values.get(key) ?? []).length === 0;
/** a view is TOTAL iff it lies in every value — every instance is also through it (vacuously so with no instance) */
export const isTotal = (values: InstanceValues, view: VertexId): boolean => [...values.values()].every((V) => V.includes(view));
/**
 * THE READINGS of the family (D7–D9 said once): the site's own part = the instances whose value is empty, its centroid = the rest; a
 * view's own part = the instances whose value lacks it, its centroid = those whose value holds it; POCKET (D8, D9) iff at least two
 * views, instances exist, no value is empty and no view is total — every view leaves something, nothing is left by all. `perView` is
 * aligned to `views` by index (two faces through one edge may share a third corner). The readers hold the parts; the family holds the truth.
 */
export function readValues(values: InstanceValues, keys: readonly string[], views: readonly VertexId[]): { own: string[]; centroid: string[]; perView: Array<{ own: string[]; centroid: string[] }>; total: VertexId[]; pocket: boolean } {
  const own = keys.filter((k) => isOwn(values, k));
  const centroid = keys.filter((k) => !isOwn(values, k));
  const perView = views.map((z) => ({ own: keys.filter((k) => !(values.get(k) ?? []).includes(z)), centroid: keys.filter((k) => (values.get(k) ?? []).includes(z)) }));
  const total = views.filter((z) => isTotal(values, z));
  const pocket = views.length >= 2 && keys.length > 0 && own.length === 0 && total.length === 0;
  return { own, centroid, perView, total, pocket };
}

/** an instance's key: `w|x|y`, and `|←` when the person said it the other way round (D13 — every key before D13 is `→` by reading) */
export const relKey = (r: Relating | [string, string, string]): string => (r.length >= 4 && dirOf(r as Relating) === AGAINST ? `${r[0]}|${r[1]}|${r[2]}|←` : `${r[0]}|${r[1]}|${r[2]}`);
const isKey = (x: string, y: string): string => `${IS}|${x}|${y}`;
const keyOf = (w: string, x: string, y: string, dir: Dir): string => (w === IS || dir === ALONG ? `${w}|${x}|${y}` : `${w}|${x}|${y}|←`);
/** every spelling a relating has under his equations (D13 — a declared converse is `y w′ x ≡ x w y`): its own key and, for a mode with a converse, the converse's key the other way round; ≡ has one spelling */
const spellingsOf = (facts: LexiconFacts, r: Relating): string[] => { const k = relKey(r); if (r[0] === IS) return [k]; const c = converseOf(facts, r[0]); return c === null ? [k] : [k, keyOf(c, r[1], r[2], dirOf(r) === ALONG ? AGAINST : ALONG)]; };
/**
 * THE SECOND RESOLUTION §6/§7 (MODES-4 · row 7) — whether a say's word `w` on (x, y) in the direction `dir` is BARRED at a sorting's
 * endpoints: by a bar of his in any of its spellings, or, for ≡, by his one-to-one law (an IS-instance at either end pairing it
 * elsewhere). The store's guard at the act reads THIS predicate — the one the sorting reads a composite against — so "no say against
 * his own bar or pair" holds by construction, whatever the passage reads at the moment of the say.
 */
export function barredAt(sorting: Sorting, facts: LexiconFacts, w: string, x: string, y: string, dir: Dir): boolean {
  if (sorting.bars.some((b) => spellingsOf(facts, b).includes(keyOf(w, x, y, dir)))) return true;
  return w === IS && sorting.instances.some((r) => r[0] === IS && ((r[1] === x && r[2] !== y) || (r[2] === y && r[1] !== x)));
}
/** his bar, in any of its spellings, that bars `w` on (x, y) in `dir` — the refusal's hand withdraws THIS relating (COPY-1 §4.3) */
export function barOf(sorting: Sorting, facts: LexiconFacts, w: string, x: string, y: string, dir: Dir): Relating | null {
  const k = keyOf(w, x, y, dir);
  return sorting.bars.find((b) => spellingsOf(facts, b).includes(k)) ?? null;
}
/** his bar whose spellings include `key` (a tension's `direct`), or null */
export function barByKey(sorting: Sorting, facts: LexiconFacts, key: string): Relating | null {
  return sorting.bars.find((b) => spellingsOf(facts, b).includes(key)) ?? null;
}

/** whether a rule reads a key: a chain in the key's own order; a fork or a join order-free (the two are one shape from one point) */
export const ruleReads = (r: Rule, k: Pick<RuleKey, 'w' | 'w2' | 'shape'>): boolean => ruleShape(r) === k.shape && ((r[0] === k.w && r[1] === k.w2) || (k.shape !== 'chain' && r[0] === k.w2 && r[1] === k.w));
/**
 * the composite of a path under the rules with its direction, or null (the identity regime's rule is always in force). A chain's
 * composite runs in the chain's own direction; a fork's or a join's takes as its subject the end he CHOSE when he named the rule
 * (M3: the end of the rule's first-named word, or the second's — never the edge's order); a same-word fork or join composes to one
 * UNDIRECTED relating (M4, §9.21): `undirected`, its direction a placeholder.
 */
export function composeBy(rules: readonly Rule[], w: string, w2: string, shape: Shape3 = 'chain', dir: Dir = ALONG): { word: string; dir: Dir; undirected: boolean } | null {
  if (w === IS && w2 === IS) return { word: IS, dir: ALONG, undirected: false }; // symmetric: every shape
  for (const r of rules) if (ruleReads(r, { w, w2, shape })) {
    if (ruleUndirected(r)) return { word: r[2], dir: ALONG, undirected: true };
    const firstNamedIsX = shape === 'chain' || r[0] === w; // the rule's first-named word's end is the walk's subject
    const subjectIsX = ruleSubject(r) === 'first' ? firstNamedIsX : !firstNamedIsX;
    return { word: r[2], dir: subjectIsX ? dir : dir === ALONG ? AGAINST : ALONG, undirected: false };
  }
  return null;
}
/** the composite a rule HE named gives, or null — the built-in IS ; IS = IS names none (an exception is read only against his rule, S6) */
export function namedBy(rules: readonly Rule[], w: string, w2: string, shape: Shape3 = 'chain'): string | null {
  for (const r of rules) if (ruleReads(r, { w, w2, shape })) return r[2];
  return null;
}
/** THE KEYS a path carries, in order (§9.14; the converse's law): its own shape's key — a chain in the chain's own order (from y, the pair reversed, the composite `←`); a fork or a join as the walk prints it — then, for a fork or a join, each chain a declared converse lets it read as (the against leg first, the along leg second) */
export function ruleKeysOf(w: string, w2: string, s1: Dir, s2: Dir, facts: LexiconFacts): RuleKey[] {
  const shape = shapeOf(s1, s2);
  if (shape === 'chain') return s1 === ALONG ? [{ w, w2, shape, dir: ALONG }] : [{ w: w2, w2: w, shape, dir: AGAINST }];
  const out: RuleKey[] = [{ w, w2, shape, dir: ALONG }];
  const cw = converseOf(facts, w); const cw2 = converseOf(facts, w2);
  if (shape === 'fork') {
    // z w x (←) · z w2 y (→): flip the first leg into its converse along ⇒ a chain x cw z · z w2 y; flip the second ⇒ a chain from y: y cw2 z · z w x
    if (cw !== null) out.push({ w: cw, w2, shape: 'chain', dir: ALONG });
    if (cw2 !== null) out.push({ w: cw2, w2: w, shape: 'chain', dir: AGAINST });
  } else {
    // x w z (→) · y w2 z (←): flip the second leg ⇒ a chain x w z · z cw2 y; flip the first ⇒ a chain from y: y w2 z · z cw x
    if (cw2 !== null) out.push({ w, w2: cw2, shape: 'chain', dir: ALONG });
    if (cw !== null) out.push({ w: w2, w2: cw, shape: 'chain', dir: AGAINST });
  }
  return out;
}

/**
 * THE SORTING of one edge from its records (the pure core): the direct relatings on e (x of X, y of Y), each view's leg
 * instances (XZ oriented X → Z, ZY oriented Z → Y — mirrored with their direction flipped where the walk runs against the
 * stored order, `relatingsFrom`), its triads (x, y, z), its verdicts (already resolved to this edge's orientation), the rules in
 * force and the lexicon's facts (the converses, the opaque modes).
 */
export function sortFromRecords(
  edge: [VertexId, VertexId],
  direct: Relating[],
  views: Array<{ view: VertexId; faceId: string; xz: Relating[]; zy: Relating[]; triads: Array<[string, string, string]>; verdicts: Array<Omit<VerdictRecord, 'base'>>; coordinate?: { edge: [VertexId, VertexId]; paths: CoordinatePath[] }; altitude?: { entries: AltitudeEntry[]; xz: Relating[]; zy: Relating[]; configuration?: ViewConfigurationInput } }>,
  rules: readonly Rule[],
  facts: LexiconFacts = NO_FACTS,
  bondRules: readonly BondRule[] = [],
): Sorting {
  const instances = direct.filter((r) => r[3] === '+');
  const bars = direct.filter((r) => r[3] === '-');
  // D13 — a declared converse is an EQUATION in the lexicon, `y w′ x ≡ x w y`: a direct (or a bar) `x c y` IS the entry `y w x`, so
  // the keys a composite is read against are CLOSED under his equations, and a composite met in the converse spelling composes
  // onto the instance he made (the mothership's 19:28: the inherited composite compared with the direct THROUGH the converses)
  const spellings = (r: Relating): string[] => spellingsOf(facts, r);
  const ownerOf = new Map<string, string>(); // every spelling of an instance → the instance's own key
  for (const r of instances) for (const k of spellings(r)) if (!ownerOf.has(k)) ownerOf.set(k, relKey(r));
  const directKeys = new Set(ownerOf.keys());
  const barKeys = new Set(bars.flatMap(spellings));
  // IS's one-to-one law as an implicit bar AT BOTH ENDS (ADR 0031 §9.7, M2 — the researcher's probe the_far_end_collision, ALL
  // SEALS HELD): the person's IS-instance (x, y′), y′ ≠ y, bars (IS, x, y), and so does (x′, y), x′ ≠ x. The law is the mode's and
  // symmetric, not the reading's direction. A path composing to a barred entry is a TENSION whichever end bars it, and the reading
  // names the end it presses on — the source's pairing (the stone's DISAGREEMENT) or the target's (a proposal onto a role already
  // paired elsewhere, which the act would refuse: a refusal placed after the act is misplaced, so it is read here). Other modes have
  // no such law; their bars are the person's entries only.
  const isX = new Map<string, string>();
  const isY = new Map<string, string>();
  for (const r of instances) if (r[0] === IS) { if (!isX.has(r[1])) isX.set(r[1], r[2]); if (!isY.has(r[2])) isY.set(r[2], r[1]); }
  /** the far-end IS-instance a composite (IS, x, y) presses on: the source's pairing first, else the target's; null when none */
  const pressedOn = (x: string, y: string): { end: 'source' | 'target'; key: string } | null => {
    const yx = isX.get(x);
    if (yx !== undefined && yx !== y) return { end: 'source', key: isKey(x, yx) };
    const xy = isY.get(y);
    if (xy !== undefined && xy !== x) return { end: 'target', key: isKey(xy, y) };
    return null;
  };
  const barred = (w: string, x: string, y: string, dir: Dir): boolean => {
    if (barKeys.has(keyOf(w, x, y, dir))) return true;
    return w === IS && pressedOn(x, y) !== null;
  };
  /** the instance keys a view's COMPOSED paths compose onto, through his equations (every spelling owned by the instance he made); M6 (4): an undirected composite with a direct in both orders composes onto both */
  const composedToOf = (read: ReadPath[]): Set<string> => new Set(read.filter((r) => r.reading === 'COMPOSED').flatMap((r) => (r.directs ?? [r.direct as string]).map((k) => ownerOf.get(k) ?? k)));
  // D18 — each view is collected with what it composes onto; its own and centroid PARTS are read from the family of values after the loop, never here
  const partial: Array<{ composedTo: Set<string>; view: Omit<ViewSorting, 'own' | 'centroid'> }> = [];
  const inheritedAll: InheritedIS[] = [];
  /** THE-ALTITUDE (D23, D25): the view's altitude as read — the marks at each END CELL spoken of (by the role's id, whichever reader lists the relating that ends there), the reach, the refusals, the emptiness */
  const altitudeViewOf = (entries: readonly AltitudeEntry[], forks: number, cfg: ViewConfigurationInput | undefined, view: VertexId, faceId: string, verdicts: Array<Omit<VerdictRecord, 'base'>>): ViewAltitude => {
    const marks = new Map<string, { present: Mark[]; denied: Mark[] }>();
    for (const s of sayingsOf(entries)) if (!marks.has(s[3])) marks.set(s[3], marksAt(entries, s[3]));
    // THE-ALTITUDE · slice 2 (R2): the bonds as passages — one per bond and per pair of his words at its two ends; read under a bond rule or his verdict,
    // against the direct relatings and the bars exactly as a path is; a refused relation of Z spans as a REFUSED ROUTE (form, no hands)
    const bonds: ReadBond[] = [];
    if (cfg) for (const b of cfg.bonds) {
      const zx = b.zAt === 'x' ? b.z : b.z2; const zy = b.zAt === 'x' ? b.z2 : b.z;
      const atX = marksAt(entries, b.x).present.filter((m) => m.z === zx);
      const atY = marksAt(entries, b.y).present.filter((m) => m.z === zy);
      for (const mx of atX) for (const my of atY) {
        const bp: BondPath = { view, faceId, x: b.x, w: mx.w, z: b.z, S: b.S, z2: b.z2, w2: my.w, y: b.y, zAt: b.zAt, holds: b.holds, said: [[zx, mx.w, b.x], [b.z, b.S, b.z2], [zy, my.w, b.y]] };
        if (!b.holds) { bonds.push({ bond: bp, composite: null, compositeDir: null, by: null, exception: false, reading: 'REFUSED', direct: null, end: null }); continue; }
        const verdict = verdicts.find((r) => r.S === b.S && r.z2 === b.z2 && r.x === b.x && r.w === mx.w && r.z === b.z && r.w2 === my.w && r.y === b.y);
        const ruled = composeBond(bondRules, mx.w, b.S, my.w);
        if (verdict && verdict.verdict === 'not') { bonds.push({ bond: bp, composite: null, compositeDir: null, by: 'verdict', exception: ruled !== null, reading: 'NOT', direct: null, end: null }); continue; }
        const composite = verdict && verdict.verdict === 'composed' && verdict.w3 ? verdict.w3 : ruled;
        const by: ReadBond['by'] = verdict && verdict.verdict === 'composed' && verdict.w3 ? 'verdict' : ruled !== null ? 'rule' : null;
        const exception = by === 'verdict' && ruled !== null && ruled !== composite;
        if (composite === null) { bonds.push({ bond: bp, composite: null, compositeDir: null, by: null, exception: false, reading: 'UNRULED', direct: null, end: null }); continue; }
        const dir: Dir = verdict && verdict.verdict === 'composed' && verdict.w3dir ? verdict.w3dir : ALONG;
        const k = keyOf(composite, b.x, b.y, dir);
        if (directKeys.has(k)) bonds.push({ bond: bp, composite, compositeDir: dir, by, exception, reading: 'COMPOSED', direct: k, end: null });
        else if (barred(composite, b.x, b.y, dir)) { const pressed = composite === IS ? pressedOn(b.x, b.y) : null; bonds.push({ bond: bp, composite, compositeDir: dir, by, exception, reading: 'TENSION', direct: pressed ? pressed.key : k, end: pressed ? pressed.end : 'bar' }); }
        else bonds.push({ bond: bp, composite, compositeDir: dir, by, exception, reading: 'LIGHT', direct: null, end: null });
      }
    }
    return { entries: entries.length, sayings: sayingsOf(entries).length, vacuousUnder: vacuousUnder(entries), reach: reachOf(entries), refusals: refusalsOf(entries), marks, forks,
      bonds, bondInstances: cfg ? cfg.counts.bondInstances : 0, cellsByBonds: cfg ? cfg.counts.cellsByBonds : 0, cellsByForks: cfg ? cfg.counts.cellsByForks : 0,
      induced: cfg ? cfg.totals.induced : 0, cut: cfg ? cfg.totals.cut : 0, cutByDenial: cfg ? cfg.totals.cutByDenial : 0, parallels: cfg ? cfg.parallels : [] };
  };
  for (const v of views) {
    if (v.coordinate) {
      // D14 — THE COORDINATE VIEW: every path is two instances holding one role of the seed corner; its reading is the generation-1
      // passage's, carried across; no key, no hand. D15 — a FIX there is an inherited IS-instance here, the face's
      const read: ReadPath[] = [];
      const inheritedHere: InheritedIS[] = [];
      for (const c of v.coordinate.paths) {
        const p: Path = { view: v.view, faceId: v.faceId, x: c.x, w: '', z: c.z, w2: '', y: c.y, source: 'coordinate', said: [[c.x, '', c.z], [c.z, '', c.y]], dirs: [ALONG, ALONG], shape: 'chain', from: 'x', keys: [], against: false, mixed: false, readable: false };
        const g = c.path;
        const inh = { edge: c.edge, corners: c.corners, q: c.q, r: c.r, path: g };
        if (!g) { read.push({ path: p, composite: null, compositeDir: null, by: null, exception: false, reading: 'UNRULED', direct: null, end: null, inherited: inh }); continue; }
        // the generation-1 path may run r → q where the parent edge is stored R first: its composite's direction is read back onto i → j
        const forward = g.path.x === c.q;
        const dirHere = (d: Dir | null): Dir | null => (d === null ? null : forward ? d : d === ALONG ? AGAINST : ALONG);
        if (g.reading === 'NOT' || g.reading === 'UNRULED' || g.reading === 'HELD') { read.push({ path: p, composite: g.composite, compositeDir: dirHere(g.compositeDir), by: g.reading === 'NOT' ? 'verdict' : null, exception: false, reading: g.reading, direct: null, end: null, inherited: inh }); continue; }
        if (g.reading === 'TENSION') { read.push({ path: p, composite: g.composite, compositeDir: dirHere(g.compositeDir), by: 'inherited', exception: false, reading: 'TENSION', direct: g.direct, end: g.end, inherited: inh }); continue; }
        const w = g.composite as string;
        // M8 (2): an UNDIRECTED composite carried across (§9.21) holds both ways here too — a direct in either order composes, a bar either way presses,
        // both a tension naming both, a light with neither; it carries no direction
        if (g.undirected) {
          const kA = keyOf(w, c.x, c.y, ALONG); const kB = keyOf(w, c.x, c.y, AGAINST);
          const directs = [kA, kB].filter((k) => directKeys.has(k));
          const direct = directs[0] ?? null;
          const bar = barred(w, c.x, c.y, ALONG) ? kA : barred(w, c.x, c.y, AGAINST) ? kB : null;
          if (direct !== null && bar !== null) read.push({ path: p, composite: w, compositeDir: null, undirected: true, by: 'inherited', exception: false, reading: 'TENSION', direct, end: 'bar', pressing: bar, inherited: inh, ...(directs.length > 1 ? { directs } : {}) });
          else if (direct !== null) read.push({ path: p, composite: w, compositeDir: null, undirected: true, by: 'inherited', exception: false, reading: 'COMPOSED', direct, end: null, inherited: inh, ...(directs.length > 1 ? { directs } : {}) });
          else if (bar !== null) read.push({ path: p, composite: w, compositeDir: null, undirected: true, by: 'inherited', exception: false, reading: 'TENSION', direct: bar, end: 'bar', inherited: inh });
          else read.push({ path: p, composite: w, compositeDir: null, undirected: true, by: 'inherited', exception: false, reading: 'LIGHT', direct: null, end: null, inherited: inh });
          continue;
        }
        const d = dirHere(g.compositeDir) as Dir;
        if (g.reading === 'COMPOSED' && w === IS) {
          // the stone's FIX at generation n−1: the person's pairing q ≡ r read here as (IS, i, j) — inherited, the face's
          const key = isKey(c.x, c.y);
          inheritedHere.push({ key, x: c.x, y: c.y, through: v.view, edge: c.edge, corners: c.corners, q: c.q, r: c.r });
          read.push({ path: p, composite: IS, compositeDir: ALONG, by: 'inherited', exception: false, reading: 'COMPOSED', direct: key, end: null, inherited: inh });
          continue;
        }
        if (g.reading === 'LIGHT' && w === IS) { read.push({ path: p, composite: IS, compositeDir: ALONG, by: 'inherited', exception: false, reading: 'LIGHT', direct: null, end: null, inherited: inh }); continue; }
        // a mode word carried across does not inherit: the face's only where he related it here, else P's light; barred here, a tension
        const k = keyOf(w, c.x, c.y, d);
        if (directKeys.has(k)) read.push({ path: p, composite: w, compositeDir: d, by: 'inherited', exception: false, reading: 'COMPOSED', direct: k, end: null, inherited: inh });
        else if (barred(w, c.x, c.y, d)) read.push({ path: p, composite: w, compositeDir: d, by: 'inherited', exception: false, reading: 'TENSION', direct: k, end: 'bar', inherited: inh });
        else read.push({ path: p, composite: w, compositeDir: d, by: 'inherited', exception: false, reading: 'LIGHT', direct: null, end: null, inherited: inh });
      }
      inheritedAll.push(...inheritedHere);
      partial.push({ composedTo: composedToOf(read), view: { view: v.view, faceId: v.faceId, coordinate: { edge: v.coordinate.edge }, vacuous: false, legs: [true, true], altitude: altitudeViewOf([], 0, undefined, v.view, v.faceId, []), paths: read, lights: read.filter((r) => r.reading === 'LIGHT'), tensions: read.filter((r) => r.reading === 'TENSION'), unruled: read.filter((r) => r.reading === 'UNRULED'), feet: new Map() } });
      continue;
    }
    const xzIn = v.xz.filter((r) => r[3] === '+');
    const zyIn = v.zy.filter((r) => r[3] === '+');
    const paths: Path[] = [];
    const saidLeg = (r: Relating): [string, string, string] => (dirOf(r) === ALONG ? [r[1], r[0], r[2]] : [r[2], r[0], r[1]]);
    for (const a of xzIn) for (const b of zyIn) if (a[2] === b[1]) {
      const s1 = dirOf(a); const s2 = dirOf(b);
      const isA = a[0] === IS; const isB = b[0] === IS;
      const mixed = isA !== isB;
      const twoModes = !isA && !isB;
      const shape = shapeOf(s1, s2);
      paths.push({ view: v.view, faceId: v.faceId, x: a[1], w: a[0], z: a[2], w2: b[0], y: b[2], source: 'legs', said: [saidLeg(a), saidLeg(b)], dirs: [s1, s2], shape, from: shape === 'chain' ? (s1 === ALONG ? 'x' : 'y') : shape === 'fork' ? 'z' : null, keys: twoModes ? ruleKeysOf(a[0], b[0], s1, s2, facts) : [], against: (s1 === AGAINST && !isA) || (s2 === AGAINST && !isB), mixed, readable: twoModes });
    }
    for (const [x, y, z] of v.triads) if (!paths.some((p) => p.x === x && p.z === z && p.y === y && p.w === IS && p.w2 === IS)) paths.push({ view: v.view, faceId: v.faceId, x, w: IS, z, w2: IS, y, source: 'triad', said: [[x, IS, z], [z, IS, y]], dirs: [ALONG, ALONG], shape: 'chain', from: 'x', keys: [], against: false, mixed: false, readable: false });
    // THE-ALTITUDE (D24): the forks of two PRESENT sayings on one z — `z w x` walked X → Z runs against (←), `z w′ y` walked Z → Y along (→); a
    // saying's word is never IS (the act refuses it), so every altitude path has two mode legs and is readable by its fork key; its own
    // source keeps it beside the legs' paths, never merged with them
    const altXZ = v.altitude ? v.altitude.xz : []; const altZY = v.altitude ? v.altitude.zy : [];
    let altitudeForks = 0;
    for (const a of altXZ) for (const b of altZY) if (a[2] === b[1]) {
      const s1 = dirOf(a); const s2 = dirOf(b);
      const shape = shapeOf(s1, s2);
      altitudeForks += 1;
      paths.push({ view: v.view, faceId: v.faceId, x: a[1], w: a[0], z: a[2], w2: b[0], y: b[2], source: 'altitude', said: [saidLeg(a), saidLeg(b)], dirs: [s1, s2], shape, from: shape === 'chain' ? (s1 === ALONG ? 'x' : 'y') : shape === 'fork' ? 'z' : null, keys: ruleKeysOf(a[0], b[0], s1, s2, facts), against: s1 === AGAINST || s2 === AGAINST, mixed: false, readable: true });
    }
    const namesPath = (r: Omit<VerdictRecord, 'base'>, p: Path): boolean => verdictNamesPath(r, p, paths);
    /** the composite a rule gives a two-mode-leg path: the first of its keys some rule reads (its own shape's key first) */
    const ruledOf = (p: Path): { word: string; dir: Dir; undirected: boolean } | null => { for (const k of p.keys) { const c = composeBy(rules, k.w, k.w2, k.shape, k.dir); if (c !== null) return c; } return null; };
    /** the composite a rule HE named gives (S6 — the exception is read against the rule of the path's own shape, or the chain a converse makes of it) */
    const namedOf = (p: Path): string | null => { for (const k of p.keys) { const c = namedBy(rules, k.w, k.w2, k.shape); if (c !== null) return c; } return null; };
    /** a verdict's composite direction: the one he CHOSE for a fork or a join (M3, `w3dir` — read on a fork or a join alone, M6 (5)); else a chain's own direction (from y: `←`); a fork or a join as the walk prints it */
    const verdictDir = (p: Path, r: Omit<VerdictRecord, 'base'>): Dir => (p.shape !== 'chain' && r.w3dir ? r.w3dir : p.from === 'y' ? AGAINST : ALONG);
    const read: ReadPath[] = paths.map((p) => {
      const verdict = v.verdicts.find((r) => namesPath(r, p));
      // the identity regime's rule is always in force (IS ; IS = IS, every shape); a rule of his reads a two-mode-leg path by its keys
      const ruled = p.readable ? ruledOf(p) : p.w === IS && p.w2 === IS ? composeBy(rules, IS, IS) : null;
      const named = p.readable ? namedOf(p) : null;
      let composite: string | null = null;
      let compositeDir: Dir | null = null;
      let by: ReadPath['by'] = null;
      let exception = false;
      if (verdict) {
        // M6 (1): against a DIRECTED rule (a fork or a join in two different words, its subject chosen) a decision in the rule's word but the
        // OTHER order is a different relating from the rule's — an exception — unless he declared the word its own converse, when the
        // other order IS the rule's relating; against an undirected rule a chosen order agrees (§9.22, a refinement)
        // M8 (1): the decision's RELATING against the rule's, through his equations (`spellingsOf`, the one spelling rule `barredAt` reads) —
        // the rule's relating in every spelling: its word in its order (an undirected rule in both orders) and the converse word the other
        // way round; a decision that is one of them agrees, any other is an exception (a converse-word decision in the SAME order is one)
        const decisionDir = verdict.verdict === 'composed' && (verdict.dirs || (p.shape !== 'chain' && verdict.w3dir)) ? verdictDir(p, verdict) : verdict.verdict === 'composed' ? ALONG : null;
        const decisionKey = verdict.verdict === 'composed' && verdict.w3 && decisionDir !== null ? keyOf(verdict.w3, p.x, p.y, decisionDir) : null;
        const ruleDirs: Dir[] = ruled === null ? [] : ruled.undirected ? [ALONG, AGAINST] : [ruled.dir];
        const ruleSpellings = named === null ? [] : ruleDirs.flatMap((d) => spellingsOf(facts, [named, p.x, p.y, '+', d] as Relating));
        exception = Boolean(verdict.exception) || (named !== null && (verdict.verdict === 'not' || decisionKey === null || !ruleSpellings.includes(decisionKey)));
        if (verdict.verdict === 'not') return { path: p, composite: null, compositeDir: null, by: 'verdict', exception, reading: 'NOT', direct: null, end: null };
        // a composed say stored on a path no hand of his reaches (a mixed path — the store refuses a new one, §9.12) is not read as a
        // composite — the path stays `not yet said` — but it is CARRIED for printing with its withdraw, never hidden (12:19 (ii))
        if (!p.readable && p.source !== 'triad') return { path: p, composite: null, compositeDir: null, by: null, exception, reading: 'UNRULED', direct: null, end: null, recorded: verdict.w3 ?? null };
        composite = verdict.w3 ?? null;
        // a record with the legs' senses speaks in the path's own direction; one without them (before D13) was said along the walk, `x w3 y`
        compositeDir = composite === null ? null : verdict.dirs || (p.shape !== 'chain' && verdict.w3dir) ? verdictDir(p, verdict) : ALONG;
        by = composite === null ? null : 'verdict';
      } else if (p.source === 'triad') {
        composite = IS; compositeDir = ALONG;
        by = 'triad';
      } else if (p.mixed) {
        // SUBSTITUTION: the identification substitutes in the relating he made (§1) — the mode leg's word with its own direction carried
        // through — through a TRANSPARENT mode only (§9.13): through an opaque mode the path composes to nothing, held apart
        const modeLeg = p.w === IS ? 1 : 0;
        const w = modeLeg === 0 ? p.w : p.w2;
        if (isOpaque(facts, w)) return { path: p, composite: null, compositeDir: null, by: null, exception, reading: 'HELD', direct: null, end: null };
        composite = w; compositeDir = p.dirs[modeLeg];
        by = 'substitution';
      } else if (ruled !== null) {
        composite = ruled.word; compositeDir = ruled.dir;
        by = 'rule';
        // M4 (ADR 0031 §9.21–§9.22): an UNDIRECTED composite — the word holding both ways between the two ends — COMPOSES where he related
        // that word between them in either direction; presses on his bar in either direction; with a direct one way AND a bar the other it
        // reads TENSION naming both (never hidden by a composed); a light only with neither
        if (ruled.undirected) {
          const kA = keyOf(composite, p.x, p.y, ALONG); const kB = keyOf(composite, p.x, p.y, AGAINST);
          const directs = [kA, kB].filter((k) => directKeys.has(k)); // M6 (4): a direct in both orders composes onto both
          const direct = directs[0] ?? null;
          const bar = barred(composite, p.x, p.y, ALONG) ? kA : barred(composite, p.x, p.y, AGAINST) ? kB : null;
          // M8 (2): an undirected composite carries NO direction (compositeDir null) — a reader that needs one cannot take a placeholder
          if (direct !== null && bar !== null) return { path: p, composite, compositeDir: null, undirected: true, by, exception, reading: 'TENSION', direct, end: 'bar', pressing: bar, ...(directs.length > 1 ? { directs } : {}) };
          if (direct !== null) return { path: p, composite, compositeDir: null, undirected: true, by, exception, reading: 'COMPOSED', direct, end: null, ...(directs.length > 1 ? { directs } : {}) };
          if (bar !== null) return { path: p, composite, compositeDir: null, undirected: true, by, exception, reading: 'TENSION', direct: bar, end: 'bar' };
          return { path: p, composite, compositeDir: null, undirected: true, by, exception, reading: 'LIGHT', direct: null, end: null };
        }
      }
      if (composite === null || compositeDir === null) return { path: p, composite: null, compositeDir: null, by: null, exception, reading: 'UNRULED', direct: null, end: null };
      const k = keyOf(composite, p.x, p.y, compositeDir);
      if (directKeys.has(k)) return { path: p, composite, compositeDir, by, exception, reading: 'COMPOSED', direct: k, end: null };
      if (barred(composite, p.x, p.y, compositeDir)) {
        // the end is TOTAL: an IS composite pressed by his pairing names that end; else the bar is his own (the only other way in)
        const pressed = composite === IS ? pressedOn(p.x, p.y) : null;
        return { path: p, composite, compositeDir, by, exception, reading: 'TENSION', direct: pressed ? pressed.key : k, end: pressed ? pressed.end : 'bar' };
      }
      return { path: p, composite, compositeDir, by, exception, reading: 'LIGHT', direct: null, end: null };
    });
    // the identity regime's kinds per x of X in Z's shadow (an IS-instance from x to Z)
    const feet = new Map<string, { kind: FootKind; y: string | null }>();
    const kindOf = (p: ReadPath): FootKind => (p.reading === 'COMPOSED' ? 'FIX' : p.reading === 'TENSION' && p.end === 'source' ? 'DIS' : p.reading === 'LIGHT' || (p.reading === 'TENSION' && p.end === 'target') ? 'PRO' : 'UND');
    for (const a of xzIn) {
      if (a[0] !== IS || feet.has(a[1])) continue;
      const p = read.find((r) => r.path.x === a[1] && r.path.z === a[2] && r.path.w === IS && r.path.w2 === IS);
      if (!p) feet.set(a[1], { kind: 'UND', y: null });
      else feet.set(a[1], { kind: kindOf(p), y: p.path.y });
    }
    for (const [x, y, z] of v.triads) if (!feet.has(x)) { const p = read.find((r) => r.path.x === x && r.path.z === z && r.path.y === y); if (p) feet.set(x, { kind: kindOf(p), y }); }
    // THE-ALTITUDE · slice 2: a COMPOSED bond composes onto its direct like a path (D6 applies to bonds as to forks); the view's value gains it
    const altitudeView = altitudeViewOf(v.altitude ? v.altitude.entries : [], altitudeForks, v.altitude ? v.altitude.configuration : undefined, v.view, v.faceId, v.verdicts);
    const composedTo = composedToOf(read);
    for (const rb of altitudeView.bonds) if (rb.reading === 'COMPOSED' && rb.direct) composedTo.add(ownerOf.get(rb.direct) ?? rb.direct);
    partial.push({ composedTo, view: { view: v.view, faceId: v.faceId, coordinate: null, altitude: altitudeView, vacuous: xzIn.length === 0 && zyIn.length === 0 && v.triads.length === 0, legs: [xzIn.length > 0 || v.triads.length > 0, zyIn.length > 0 || v.triads.length > 0], paths: read, lights: read.filter((r) => r.reading === 'LIGHT'), tensions: read.filter((r) => r.reading === 'TENSION'), unruled: read.filter((r) => r.reading === 'UNRULED'), feet } });
  }
  // D18 — THE FAMILY OF VALUES, read once; every part and token below is a reading of it (with no view every value is empty: all own)
  const keys = instances.map(relKey);
  const values = valuesOf(keys, partial.map((p) => ({ view: p.view.view, composedTo: p.composedTo })));
  const R = readValues(values, keys, partial.map((p) => p.view.view));
  const out: ViewSorting[] = partial.map((p, i) => ({ ...p.view, own: R.perView[i].own, centroid: R.perView[i].centroid }));
  const ownAll = R.own;
  const centroidAll = R.centroid;
  const pocket = R.pocket;
  // THE-ALTITUDE · slice 2: a bond is a passage too — a view holding one is looked at, and one nobody has said is unruled (REFUSED routes are form, neither)
  const looked = out.some((v) => v.paths.length > 0 || v.altitude.bonds.some((b) => b.reading !== 'REFUSED'));
  const unruled = out.some((v) => v.unruled.length > 0 || v.altitude.bonds.some((b) => b.reading === 'UNRULED'));
  const tension = out.some((v) => v.tensions.length > 0);
  // D16's refused route (the second resolution §4; §9.11): a NOT on a path whose word — the rule's composite, or the word the NOT
  // record itself names (`w3` on a NOT stored before M3 S5, when the hand named a standing direct's word) — has a direct standing at
  // its endpoints: the instance stays own against that path and the refusal is its FORM, kept per instance with the views through
  // which the route was refused; never a state, never a tension; it does NOT bar COHERENT (M4 corrected: "pending" struck)
  const refused = new Map<string, VertexId[]>();
  for (const v of out) for (const r of v.paths) {
    if (r.reading !== 'NOT') continue;
    const rec = views.find((w) => w.view === v.view)?.verdicts.find((h) => h.verdict === 'not' && h.x === r.path.x && h.w === r.path.w && h.z === r.path.z && h.w2 === r.path.w2 && h.y === r.path.y);
    const wordOfNot = ((): { word: string; dir: Dir; undirected?: boolean } | null => {
      // the word the NOT record names was offered as `x w3 y` — a record with the legs' senses reads its composite in the path's own
      // direction; one without them (before D13) was offered along the walk, whatever the legs' senses read as now
      if (rec?.w3) return { word: rec.w3, dir: rec.dirs && r.path.from === 'y' ? AGAINST : ALONG };
      if (!r.path.readable) return null;
      for (const k of r.path.keys) { const c = composeBy(rules, k.w, k.w2, k.shape, k.dir); if (c !== null) return c; }
      return null;
    })();
    if (!wordOfNot) continue;
    // M6 (3): an undirected composite (§9.21) holds both ways, so the route it refuses is to a direct in EITHER order
    const keys = wordOfNot.undirected ? [keyOf(wordOfNot.word, r.path.x, r.path.y, ALONG), keyOf(wordOfNot.word, r.path.x, r.path.y, AGAINST)] : [keyOf(wordOfNot.word, r.path.x, r.path.y, wordOfNot.dir)];
    for (const key of keys) if (directKeys.has(key)) { const own = ownerOf.get(key) ?? key; refused.set(own, [...(refused.get(own) ?? []), v.view]); }
  }
  const refusedRoutes = [...refused.values()].reduce((n, vs) => n + vs.length, 0);
  // a verdict disagreement: one word-pair composed to different words across faces
  const said = new Map<string, Set<string>>();
  for (const v of out) for (const r of v.paths) if (r.by === 'verdict' && r.composite !== null) { const k = `${r.path.w}|${r.path.w2}`; said.set(k, new Set([...(said.get(k) ?? []), r.composite])); }
  const disagreement = [...said.values()].some((s) => s.size > 1);
  const light = out.some((v) => v.lights.length > 0);
  // the second resolution §8 (D8 amended): COHERENT presupposes that the site has been LOOKED AT — a passage through some view —
  // and that no passage is UNRULED; then no tension, no disagreement, no pocket. With no passage at all the site is VACUOUS (its
  // own state). THE STATE is one token at §8's precedence (MODES-2 (d)); the flags beside it stay for the readers that hold them
  const coherent = looked && !unruled && !tension && !disagreement && !pocket;
  // the `closed` FLAG as built (a reader holds it: the medium's root attribute): on a lightless POCKET it reads true where D18's CLOSED
  // (no value empty, some view total, no light — §9.20) reads false; the built token stands (the mothership's 10:49 §1) and the
  // difference is reported, not hidden. THE STATE's tokens agree with D18 everywhere: POCKET takes precedence below, and past it "no
  // value empty and instances exist" entails a total view (one view: it is in every value; two or more without one: a pocket)
  const closed = instances.length > 0 && ownAll.length === 0 && !light;
  const state: Sorting['state'] = instances.length === 0 && bars.length === 0 ? 'UNDETECTED'
    : !looked ? 'VACUOUS'
      : unruled ? 'UNRULED'
        : pocket ? 'POCKET'
          : ownAll.length === 0 && instances.length > 0 ? (light ? 'EXHAUSTED' : 'CLOSED')
            : coherent ? 'COHERENT'
              : 'OPEN';
  return { edge, instances, bars, views: out, own: ownAll, centroid: centroidAll, inherited: inheritedAll, state, looked, refusedRoutes, refused, unruled, coherent, closed, values, total: R.total };
}

/** whether a verdict record names a path: by its five names and, where the record carries them, the legs' senses; a record WITHOUT
 *  `dirs` (every record before D13 — the senses were then the stored order's) names the one path with those five names, or the
 *  `→ →` one where the person has since said the same words the other way round too */
export function verdictNamesPath(r: Pick<VerdictRecord, 'x' | 'w' | 'z' | 'w2' | 'y' | 'dirs' | 'S'>, p: Pick<Path, 'x' | 'w' | 'z' | 'w2' | 'y' | 'dirs'>, paths: ReadonlyArray<Pick<Path, 'x' | 'w' | 'z' | 'w2' | 'y' | 'dirs'>>): boolean {
  if (r.S !== undefined) return false; // THE-ALTITUDE · slice 2: a verdict on a BOND names no path
  const five = (q: Pick<Path, 'x' | 'w' | 'z' | 'w2' | 'y'>): boolean => r.x === q.x && r.w === q.w && r.z === q.z && r.w2 === q.w2 && r.y === q.y;
  if (!five(p)) return false;
  if (r.dirs) return r.dirs[0] === p.dirs[0] && r.dirs[1] === p.dirs[1];
  const along = p.dirs[0] === ALONG && p.dirs[1] === ALONG;
  return along || !paths.some((q) => q !== p && five(q) && q.dirs[0] === ALONG && q.dirs[1] === ALONG);
}

/** the verdicts a face holds, positional (well-formed items only) */
export function verdictsOn(face: Face | undefined): VerdictRecord[] {
  const raw = face?.data?.[VERDICTS_KEY];
  if (!Array.isArray(raw)) return [];
  return (raw as unknown[]).filter((v): v is VerdictRecord => {
    if (!v || typeof v !== 'object' || Array.isArray(v)) return false;
    const o = v as Record<string, unknown>;
    const word = (k: string): boolean => typeof o[k] === 'string' && (o[k] as string).length > 0;
    // a `composed` say names the direct's mode; a `not` say speaks of no direct and may carry none (M3 S5); the legs' senses, absent, are both `→` (D13)
    const isDir = (d: unknown): boolean => d === ALONG || d === AGAINST;
    // M6 (5): a chosen order (`w3dir`) is a fork's or a join's alone and is `→` or `←` — a record saying otherwise is not read (its bytes stay)
    const legs = Array.isArray(o.dirs) && o.dirs.length === 2 && isDir(o.dirs[0]) && isDir(o.dirs[1]) ? shapeOf(o.dirs[0] as Dir, o.dirs[1] as Dir) : 'chain';
    if (o.w3dir !== undefined && !(isDir(o.w3dir) && legs !== 'chain')) return false;
    return Array.isArray(o.base) && o.base.length === 2 && o.base.every((n) => typeof n === 'number') && ['x', 'w', 'z', 'w2', 'y'].every(word) && ((o.verdict === 'composed' && word('w3')) || (o.verdict === 'not' && (o.w3 === undefined || word('w3')))) && (o.dirs === undefined || (Array.isArray(o.dirs) && o.dirs.length === 2 && o.dirs.every(isDir)));
  }).map((v) => ({ ...v, base: [v.base[0], v.base[1]] }));
}
/** two records name one path when their senses agree — or when either carries none (a record before D13 and its successor are one path's) */
const sameDirsOf = (a: [Dir, Dir] | undefined, b: [Dir, Dir] | undefined): boolean => !a || !b || (a[0] === b[0] && a[1] === b[1]);
const samePath = (h: VerdictRecord, v: Pick<VerdictRecord, 'base' | 'x' | 'w' | 'z' | 'w2' | 'y' | 'dirs' | 'S' | 'z2'>): boolean => (h.S ?? null) === (v.S ?? null) && (h.z2 ?? null) === (v.z2 ?? null) && h.base[0] === v.base[0] && h.base[1] === v.base[1] && h.x === v.x && h.w === v.w && h.z === v.z && h.w2 === v.w2 && h.y === v.y && sameDirsOf(h.dirs, v.dirs);
export function withVerdict(face: Face, v: VerdictRecord): Face {
  const held = verdictsOn(face).filter((h) => !samePath(h, v));
  const rest: PacketData = { ...(face.data ?? {}) };
  rest[VERDICTS_KEY] = [...held, { ...v }] as unknown as JsonValue;
  return { ...face, data: rest };
}
export function withoutVerdict(face: Face, v: Omit<VerdictRecord, 'verdict' | 'w3' | 'exception'>): Face {
  const held = verdictsOn(face);
  const next = held.filter((h) => !samePath(h, v));
  if (next.length === held.length) return face;
  const rest: PacketData = { ...(face.data ?? {}) };
  delete rest[VERDICTS_KEY];
  if (next.length) rest[VERDICTS_KEY] = next as unknown as JsonValue;
  return Object.keys(rest).length ? { ...face, data: rest } : (({ data: _d, ...f }) => { void _d; return f; })(face);
}

/** an edge's instances and bars oriented from `from` to `to` (the record reads first corner ↦ second): walked against the stored order, each relating is MIRRORED — x ↔ y with its direction flipped (D13) — never a word kept on swapped coordinates */
export function relatingsFrom(shape: Shape, from: VertexId, to: VertexId, options: SpaceOfOptions): Relating[] {
  const e = edgeBetween(shape.edges, from, to);
  if (!e) return [];
  const list = [...instancesOn(e, options), ...barsOn(e, options)];
  return e.vertexIds[0] === from ? list : list.map(mirrored);
}
/** whether a walk from `from` to `to` runs AGAINST the edge's stored order (the record's direction is the edge's orientation, §212) */
export function legAgainst(shape: Shape, from: VertexId, to: VertexId): boolean {
  const e = edgeBetween(shape.edges, from, to);
  return !!e && e.vertexIds[0] !== from;
}

/** THE SORTING of an edge on a shape: every triangular face through it a view; the legs, the triads and the verdicts read from the shape; the rules and the lexicon's facts given */
/** THE-ALTITUDE · slice 2: what `sortingOf` hands a view of its configuration — the bonds across the cells, the counts, the totals, the parallels on both ends */
export interface ViewConfigurationInput { bonds: Bond[]; counts: ReturnType<typeof bondCounts>; totals: { induced: number; cut: number; cutByDenial: number }; parallels: Parallel[] }
export function sortingOf(shape: Shape, edge: Edge | undefined, options: SpaceOfOptions = {}, rules: readonly Rule[] = [], facts: LexiconFacts = NO_FACTS, bondRules: readonly BondRule[] = []): Sorting | null {
  if (!edge) return null;
  const [X, Y] = edge.vertexIds as [VertexId, VertexId];
  // D15 (b): the medium's IS-instances are his pairings AND the inherited ones (a FIX one generation down, read here) — the same
  // reader the child uses, so the head, the child line and the born-room sentence count as one (§149)
  const direct = [...instancesWithInherited(shape, edge, options), ...barsOn(edge, options)];
  const triadsBy = respectsOn(shape, edge);
  // D14 — a MEDIAL edge's shared parent P (X = ⟨P, Q⟩, Y = ⟨P, R⟩): P's view is read from the coordinate map, not from relatings
  const parentsOf = (v: VertexId): VertexId[] => { const w = shape.vertices[v]; return !w || w.createdBy.operation === 'seed' ? [] : [...w.createdBy.sourceVertexIds]; };
  const px = parentsOf(X); const py = parentsOf(Y);
  const P = px.length === 2 && py.length === 2 ? (px.find((v) => py.includes(v)) ?? null) : null;
  const coordinateView = (): { edge: [VertexId, VertexId]; paths: CoordinatePath[] } | null => {
    if (P === null) return null;
    const Q = px.find((v) => v !== P) as VertexId; const R = py.find((v) => v !== P) as VertexId;
    const eQR = edgeBetween(shape.edges, Q, R);
    if (!eQR) return null;
    const ePQ = edgeBetween(shape.edges, P, Q); const ePR = edgeBetween(shape.edges, P, R);
    if (!ePQ || !ePR) return null;
    const xs = instancesFrom(shape, P, Q, options); const ys = instancesFrom(shape, P, R, options);
    const parent = sortingOf(shape, eQR, options, rules, facts);
    const view = parent ? parent.views.find((v) => v.view === P) : undefined;
    const qFirst = eQR.vertexIds[0] === Q;
    // the generation-1 path from q to r through P is the one whose two legs ARE i's and j's relatings walked along the parent edge
    const legOf = (g: Path, n: 0 | 1): Relating => (n === 0 ? relating(g.w, g.x, g.z, '+', g.dirs[0]) : relating(g.w2, g.z, g.y, '+', g.dirs[1]));
    const paths: CoordinatePath[] = [];
    for (const i of xs) for (const j of ys) if (i.p === j.p) {
      const iToP = ePQ.vertexIds[0] === Q ? i.rel : mirrored(i.rel); // i's relating walked Q → P
      const pToJ = ePR.vertexIds[0] === P ? j.rel : mirrored(j.rel); // j's walked P → R
      const [leg1, leg2] = qFirst ? [iToP, pToJ] : [mirrored(pToJ), mirrored(iToP)];
      const g = view ? view.paths.find((pp) => pp.path.z === i.p && (pp.path.source === 'triad' ? (pp.path.x === leg1[1] && pp.path.y === leg2[2] && leg1[0] === IS && leg2[0] === IS) : (sameEntry(legOf(pp.path, 0), leg1) && sameEntry(legOf(pp.path, 1), leg2)))) ?? null : null;
      // the pair in the PASSAGE's own order (her 10:57 §3: `your pair r0 ≡ Φ8` — X's side first): q of Q (X's other parent), r of R (Y's)
      paths.push({ x: i.key, z: i.p, y: j.key, edge: [eQR.vertexIds[0] as VertexId, eQR.vertexIds[1] as VertexId], corners: [Q, R], q: i.q, r: j.q, path: g });
    }
    return { edge: [eQR.vertexIds[0] as VertexId, eQR.vertexIds[1] as VertexId], paths };
  };
  // THE-ALTITUDE: the ends' roles, to place a saying's end-cell (the modes layer's reader — a seed's cast, a born corner's own child)
  const rolesX = new Set((childSpaceOf(shape, X, options)?.roles ?? []).map((r) => r.id));
  const rolesY = new Set((childSpaceOf(shape, Y, options)?.roles ?? []).map((r) => r.id));
  const views = facesThrough(shape, edge).map((f) => {
    const Z = f.vertexIds.find((v) => v !== X && v !== Y) as VertexId;
    const iX = f.vertexIds.indexOf(X);
    const iY = f.vertexIds.indexOf(Y);
    if (Z === P) { const cv = coordinateView(); if (cv) return { view: Z, faceId: f.id, xz: [], zy: [], triads: [], verdicts: [], coordinate: cv }; }
    const rec = triadsBy.get(Z);
    // the triad's tuple reads a of the edge's first corner, b of its second, c of the light — the edge's own orientation already
    const triads: Array<[string, string, string]> = rec ? rec.roles.map((t) => [t[0], t[1], t[2]] as [string, string, string]) : [];
    const verdicts = verdictsOn(f).filter((v) => v.base[0] === iX && v.base[1] === iY).map(({ base: _b, ...rest }) => { void _b; return rest; });
    // THE-ALTITUDE: the opposite corner's record at this face, its present sayings as legs in the walk's form (altitude.ts)
    const alt = altitudeOf(shape, f.id, Z);
    const entries = alt ? alt.entries : [];
    // THE-ALTITUDE · slice 2 (§9.30): the configuration of Z through its altitude — the bonds across the cells, the counts, the parallels on each end
    const ZS = childSpaceOf(shape, Z, options); const XS = childSpaceOf(shape, X, options); const YS = childSpaceOf(shape, Y, options);
    const rx = [...rolesX]; const ry = [...rolesY];
    const configuration: ViewConfigurationInput | undefined = entries.length > 0 ? { bonds: bondsAcross(ZS, entries, rx, ry), counts: bondCounts(ZS, entries, rx, ry), totals: (({ induced, cut, cutByDenial }) => ({ induced, cut, cutByDenial }))(configurationTotals(ZS, entries, [...rx, ...ry])), parallels: [...parallelsOn(XS, ZS, entries), ...parallelsOn(YS, ZS, entries)] } : undefined;
    const altitude = { entries, ...altitudeLegs(entries, rolesX, rolesY), configuration };
    return { view: Z, faceId: f.id, xz: relatingsFrom(shape, X, Z, options), zy: relatingsFrom(shape, Z, Y, options), triads, verdicts, altitude };
  });
  // several Face objects with one vertex set are one view (a face two cells hold): keep the first per light
  const seen = new Set<VertexId>();
  const oneEach = views.filter((v) => { if (seen.has(v.view)) return false; seen.add(v.view); return true; });
  return sortFromRecords([X, Y], direct, oneEach, rules, facts, bondRules);
}

/** THE LOOP at a base corner X of a face X·Y·Z — the face reading's classification, from the same paths: h(x) is the direct on
 *  X–Y then the path back from y through Z; returned to itself (Fix), elsewhere (Mov), or broke — at step 1 (no direct), 2 or 3 */
export type LoopStep = 1 | 2 | 3;
export function loopReading(xy: Map<string, string>, yz: Map<string, string>, zx: Map<string, string>, rolesX: readonly string[]): { fix: string[]; mov: Array<[string, string]>; und: Array<{ role: string; brokeAt: LoopStep }> } {
  // D20 — the loop IS the monodromy of the three maps (one function with the face reading and the cargo's walk); the break's step 1 · 2 · 3
  const m = monodromyOf([xy, yz, zx], rolesX);
  return { fix: m.fix, mov: m.mov, und: m.und.map((u) => ({ role: u.role, brokeAt: (u.brokeAt + 1) as LoopStep })) };
}
/** the IS map of an edge from `from` to `to` (the first IS-instance per x) */
export function isMapFrom(shape: Shape, from: VertexId, to: VertexId, options: SpaceOfOptions = {}): Map<string, string> {
  const m = new Map<string, string>();
  for (const r of relatingsFrom(shape, from, to, options)) if (r[0] === IS && r[3] === '+' && !m.has(r[1])) m.set(r[1], r[2]);
  return m;
}
